def build_converted():
    name = "converted_wells"
    n = 96
    dates = month_dates(n)
    conv = 48
    wells = ["I-1", "I-2", "P-1", "P-2", "P-3", "P-4", "P-5"]
    coords = {
        "I-1": (1000, 2000, 2400),
        "I-2": (5000, 2000, 2410),
        "P-1": (2000, 1000, 2405),
        "P-2": (2000, 3000, 2402),
        "P-3": (3000, 2000, 2408),
        "P-4": (4000, 1000, 2404),
        "P-5": (4000, 3000, 2406),
    }
    cat = {w: ("ALPHA", "A-SAND", "BLK-2") for w in coords}

    # phase A (months 0-47): injectors I-1,I-2 ; producers P-1..P-5
    # phase B (48-95): P-2 and P-5 converted to injectors -> injectors I-1,I-2,P-2,P-5 ; producers P-1,P-3,P-4
    def Fmat(injs, prods, boost=None):
        F = np.zeros((len(injs), len(prods)))
        for i, wi in enumerate(injs):
            for j, wj in enumerate(prods):
                F[i, j] = 1 / math.dist(coords[wi][:2], coords[wj][:2]) ** 2
        return F / F.sum(axis=1, keepdims=True) * 0.9

    injA = ["I-1", "I-2"]
    prodA = ["P-1", "P-2", "P-3", "P-4", "P-5"]
    injB = ["I-1", "I-2", "P-2", "P-5"]
    prodB = ["P-1", "P-3", "P-4"]
    FA = Fmat(injA, prodA)
    FB = Fmat(injB, prodB)
    tauA = np.array([30, 32, 25, 31, 33.0])
    tauB = np.array([26, 20, 27.0])
    sig = np.column_stack(
        [
            inj_signal(n, 1800, 400, 15, 0, 300),
            inj_signal(n, 1700, 380, 18, 1, 301),
            inj_signal(n, 900, 200, 13, 2, 302),
            inj_signal(n, 950, 220, 17, 3, 303),
        ]
    )
    qA = crm_forward(sig[:conv, :2], FA, tauA, q0=np.full(5, 600.0))
    qB = crm_forward(sig[conv:, :], FB, tauB, q0=np.array([qA[-1, 0], qA[-1, 2], qA[-1, 3]]))
    # assemble per-well series in canonical well order (all 7 wells as both possible roles)
    inj_all = np.zeros((n, 4))
    inj_all[:conv, :2] = sig[:conv, :2]
    inj_all[conv:, :] = sig[conv:, :]
    qliq = np.zeros((n, 5))
    qliq[:conv] = qA
    qliq[conv:, [0, 2, 3]] = qB
    cwi = np.cumsum(qliq, axis=0) * 30
    fo = oil_cut(cwi, np.full(5, 3e-7), np.full(5, 1.5))
    inj_names = ["I-1", "I-2", "P-2", "P-5"]
    prod_names = prodA
    inj_by_month = [[True, True, t >= conv, t >= conv] for t in range(n)]
    role = [[True, t < conv, True, True, t < conv] for t in range(n)]
    bhp = np.column_stack(
        [1550 - 2 * np.arange(n) + 25 * np.sin(np.arange(n) / 10 + j) for j in range(5)]
    )
    truth = {
        "case": name,
        "n_months": n,
        "conversion_month_index": conv,
        "conversion_date": dates[conv],
        "converted_wells": {"P-2": "producer->injector", "P-5": "producer->injector"},
        "expected_well_types": {
            "I-1": "INJ",
            "I-2": "INJ",
            "P-1": "PROD",
            "P-3": "PROD",
            "P-4": "PROD",
            "P-2": "MIXED",
            "P-5": "MIXED",
        },
        "phase_A": {
            "injectors": injA,
            "producers": prodA,
            "f_ij": {
                injA[i]: {prodA[j]: round(float(FA[i, j]), 4) for j in range(5)} for i in range(2)
            },
            "tau_days": dict(zip(prodA, tauA.tolist())),
        },
        "phase_B": {
            "injectors": injB,
            "producers": prodB,
            "f_ij": {
                injB[i]: {prodB[j]: round(float(FB[i, j]), 4) for j in range(3)} for i in range(4)
            },
            "tau_days": dict(zip(prodB, tauB.tolist())),
        },
        "pvt": PVT,
        "bhp_available": True,
        "expected_behaviour": "loader derives MIXED with conversion at 2020-01; engine splits history at that date and fits two windows",
        "acceptance": {
            "well_type_exact": True,
            "window_split_exact": True,
            "phase_B_f_ij_tolerance_pct": 15,
        },
    }
    rd = f"# {name}\n\nP-2 and P-5 convert from producer to injector at {dates[conv]}. Tests well-type derivation, role splitting and window segmentation.\n"
    write_case(
        name,
        dates,
        inj_names,
        prod_names,
        inj_all,
        qliq,
        fo,
        coords,
        cat,
        truth,
        rd,
        bhp=bhp,
        prod_noise=0.03,
        role_table=role,
        inj_names_by_month=inj_by_month,
        extra_events=[
            ("P-2", dates[conv], "CONVERSION", "producer to injector"),
            ("P-5", dates[conv], "CONVERSION", "producer to injector"),
        ],
    )


build_converted()


# ================================================================ sectored_60
def build_sectored():
    name = "sectored_60"
    n = 96
    dates = month_dates(n)
    coords = {}
    cat = {}
    inj_names = []
    prod_names = []
    for s, (sx, sy, blk) in enumerate([(0, 0, "SEC-N"), (12000, 0, "SEC-S")]):
        for k in range(30):
            x = sx + 1000 + (k % 6) * 1600
            y = sy + 1000 + (k // 6) * 1400
            w = f"I-{s + 1}{k:02d}" if (k % 6 + k // 6) % 2 == 0 else f"P-{s + 1}{k:02d}"
            coords[w] = (x, y, 2700 + s * 40)
